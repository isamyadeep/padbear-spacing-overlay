/**
 * Extracts the Padbear Module 1 engine (the longest inline <script> in
 * index.html) into a standalone `padbear-engine.js` that can be injected into
 * ANY page via a <script> tag or DevTools paste. Single source of truth stays
 * index.html — re-run this after editing the engine:
 *
 *   node tools/extract-engine.mjs
 *
 * Also syncs the engine's snapshot `version` field from package.json
 * (padbear-npm/package.json), so the package version and the engine build
 * can never drift. Index.html is rewritten in place when they differ.
 *
 * The file is named padbear-engine.js — deliberately NOT padbear.js. On
 * Windows, cmd.exe resolves commands from the current directory first, so a
 * project containing padbear.js would shadow the `padbear` CLI command
 * (npx padbear → the local .js file → file-association chaos). v0.2.0.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const VERSION_RE = /(tool:\s*'Padbear',\s*version:\s*')[^']*(')/;

const pkg = JSON.parse(
  readFileSync(new URL('../padbear-npm/package.json', import.meta.url), 'utf8'),
);
const version = pkg.version;
if (!version) throw new Error('padbear-npm/package.json has no version field');

let html = readFileSync(new URL('../index.html', import.meta.url), 'utf8');
const scripts = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map((m) => m[1]);
if (!scripts.length) throw new Error('No inline <script> blocks found in index.html');

// Module 1 is by far the longest script (the other one is the demo tokens).
let engine = scripts.reduce((a, b) => (b.length > a.length ? b : a));

// ---- sync the snapshot version stamp -------------------------------------
if (!VERSION_RE.test(engine)) {
  throw new Error("engine has no `tool: 'Padbear', version: '…'` stamp to sync");
}
const stamped = engine.replace(VERSION_RE, `$1${version}$2`);
if (stamped !== engine) {
  console.log(`✓ engine version stamp → ${version}`);
  engine = stamped;
  html = html.replace(VERSION_RE, `$1${version}$2`);
  writeFileSync(new URL('../index.html', import.meta.url), html);
}

const header = `/* Padbear engine — AUTO-EXTRACTED from index.html by tools/extract-engine.mjs.
   Do not edit this file; edit index.html and re-run:  node tools/extract-engine.mjs
   Inject into any page:  <script src=".../padbear-engine.js"></script>  */\n`;

// Output lives in padbear-npm/ — that folder IS the npm package.
writeFileSync(new URL('../padbear-npm/padbear-engine.js', import.meta.url), header + engine.trim() + '\n');
console.log(`padbear-npm/padbear-engine.js written (${engine.split('\n').length} lines, v${version})`);
